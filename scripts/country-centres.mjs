#!/usr/bin/env node
// Writes lib/ti/geo/country-centres.ts: for every country in world-atlas's 50m
// outline, its ISO alpha-2 code, the centre of its largest landmass, and the
// numeric id the 110m outline knows it by.
//
// The rail's globe needs this when a result has a country but no point, which
// is most domains. Matching on the provider's country name does not work: the
// atlas abbreviates ("Bosnia and Herz.", "Dem. Rep. Congo") and providers do
// not. The centre is the largest polygon's rather than the whole country's, so
// France lands in France and not in the Atlantic between it and French Guiana.
//
//   node scripts/country-centres.mjs
import { geoArea, geoCentroid } from "d3-geo";
import countries from "i18n-iso-countries";
import { feature } from "topojson-client";
import { readFileSync, writeFileSync } from "node:fs";

const atlas = JSON.parse(readFileSync("node_modules/world-atlas/countries-50m.json", "utf8"));
const features = feature(atlas, atlas.objects.countries).features;

// The atlas leaves these without an ISO numeric id; Kosovo has a user-assigned
// alpha-2 that providers do send.
const UNNUMBERED = { Kosovo: "XK" };

function largestPart(f) {
  if (f.geometry.type !== "MultiPolygon") return f;
  const parts = f.geometry.coordinates.map((coordinates) => ({ type: "Polygon", coordinates }));
  return parts.reduce((a, b) => (geoArea(b) > geoArea(a) ? b : a));
}

// Some ids name more than one feature (Ashmore and Cartier is filed under
// Australia's), so each code keeps its largest.
const byCode = new Map();
for (const f of features) {
  const code = f.id ? countries.numericToAlpha2(f.id) : UNNUMBERED[f.properties.name];
  if (!code) continue;
  const area = geoArea(f);
  if ((byCode.get(code)?.area ?? -1) < area) byCode.set(code, { f, area });
}
const rows = [...byCode].map(([code, { f }]) => {
  const [lon, lat] = geoCentroid(largestPart(f));
  return [code, +lon.toFixed(2), +lat.toFixed(2), f.id ?? ""];
});
rows.sort((a, b) => a[0].localeCompare(b[0]));

const body = rows
  .map(([code, lon, lat, id]) => `  ${code}: [${lon}, ${lat}${id ? `, "${id}"` : ""}],`)
  .join("\n");
writeFileSync(
  "lib/ti/geo/country-centres.ts",
  `// Generated by scripts/country-centres.mjs from world-atlas's 50m outline.
// Do not edit by hand; rerun the script.

/** ISO alpha-2 -> [lon, lat] of the largest landmass, and the atlas's numeric
 *  id when it has one, which is how the 110m outline names the country. */
export const COUNTRY_CENTRES: Record<string, readonly [number, number, string?]> = {
${body}
};
`,
);
console.log(`${rows.length} countries`);
